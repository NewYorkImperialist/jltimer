// @ts-check
"use strict";

// jlTimer bandaged puzzles (menu Special > Bandaged Cube): the Bicube model shared by the scramble image
// (tools/image.js) and the virtual puzzle (twisty/twistybandaged.js), plus what the bandaged Square-1 needs.
//
// Bicube (event "bic", Meffert's Bicube, analysed on Jaap's Puzzle Page, jaapsch.net/puzzles/bandage.htm): a 3x3x3
// with pieces glued together. Seven corners are glued to an edge each, making seven 2x1x1 blocks; the remaining
// five edges are glued to face centres: UL to the U centre, RB to the R centre, FD to the F centre, LD to the L
// centre, and DB to both the D and the B centre. The UFR corner is free. So D and B can never turn, slices never
// can, and U / F / L / R turn only when that layer holds whole blocks. 440 shapes x 7!/2 = 1,108,800 positions.
// csTimer's scrambler (scramble/utilscramble.js, bicube) tracks exactly this bandaging and only makes legal turns.
//
// Coordinates: a cubie is an integer vector, x towards R, y towards U, z towards F; a sticker is its cubie plus an
// outward normal. Moves use the twisty NxN format [layerStart, layerEnd, face, quarterTurns]: layers count from
// the face (1 = the face layer), so [1, 3, face, q] (or a larger layerEnd) turns the whole puzzle.
//
// Bandaged Square-1 </,(1,0)> (event "bsq", csTimer's sq1_scramble type 2): the puzzle generated by the slice and
// top-layer turns only. Built as a Square-1 with one bottom piece glued to the half of the middle layer that the
// slice does not turn (the left half seen from the front). The bottom layer can then never turn, the slice turns
// as usual and the top turns freely: that is exactly </,(1,0)>. The virtual puzzle (twisty/twistybandaged.js)
// draws the glued piece joined to the middle layer and refuses turns that would split it.
var puzzleBandaged = (function() {
	var FACES = 'URFDLB';
	/** @type {number[][]} outward normals in URFDLB order */
	var NORMALS = [[0, 1, 0], [1, 0, 0], [0, 0, 1], [0, -1, 0], [-1, 0, 0], [0, 0, -1]];

	// the glued blocks of the Bicube, by home position (the free UFR corner is a block of its own)
	var BLOCKS = [
		[[-1, 1, -1], [0, 1, -1]], // UBL + UB
		[[1, 1, -1], [1, 1, 0]], // UBR + UR
		[[-1, 1, 1], [0, 1, 1]], // UFL + UF
		[[-1, -1, 1], [-1, 0, 1]], // DFL + FL
		[[-1, -1, -1], [-1, 0, -1]], // DBL + BL
		[[1, -1, 1], [1, 0, 1]], // DFR + FR
		[[1, -1, -1], [1, -1, 0]], // DBR + DR
		[[0, 1, 0], [-1, 1, 0]], // U centre + UL
		[[1, 0, 0], [1, 0, -1]], // R centre + RB
		[[0, 0, 1], [0, -1, 1]], // F centre + FD
		[[-1, 0, 0], [-1, -1, 0]], // L centre + LD
		[[0, -1, 0], [0, -1, -1], [0, 0, -1]], // D centre + DB + B centre
		[[1, 1, 1]] // UFR, free
	];

	function dot(a, b) {
		return a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
	}

	function same(a, b) {
		return a[0] == b[0] && a[1] == b[1] && a[2] == b[2];
	}

	// a quarter turn of v, clockwise when looking at the face whose outward normal is n (as in lib/puzzle112.js)
	function quarter(v, n) {
		var d = dot(n, v);
		return [
			d * n[0] + v[1] * n[2] - v[2] * n[1],
			d * n[1] + v[2] * n[0] - v[0] * n[2],
			d * n[2] + v[0] * n[1] - v[1] * n[0]
		];
	}

	/**
	 * the block of a home position, or -1 (the core)
	 * @param {number[]} home
	 */
	function blockOf(home) {
		for (var b = 0; b < BLOCKS.length; b++) {
			for (var i = 0; i < BLOCKS[b].length; i++) {
				if (same(BLOCKS[b][i], home)) {
					return b;
				}
			}
		}
		return -1;
	}

	/**
	 * solved Bicube: 26 cubies {home, pos, block, stickers: [{col, n}]}
	 * @returns {any}
	 */
	function solved() {
		var cubies = [];
		for (var x = -1; x <= 1; x++) {
			for (var y = -1; y <= 1; y++) {
				for (var z = -1; z <= 1; z++) {
					if (!x && !y && !z) {
						continue;
					}
					var home = [x, y, z];
					var stickers = [];
					for (var f = 0; f < 6; f++) {
						if (dot(home, NORMALS[f]) == 1) {
							stickers.push({ col: f, n: NORMALS[f].slice() });
						}
					}
					cubies.push({ home: home, pos: home.slice(), block: blockOf(home), stickers: stickers });
				}
			}
		}
		return { cubies: cubies };
	}

	/** @param {any} st */
	function clone(st) {
		return {
			cubies: st.cubies.map(function(c) {
				return {
					home: c.home, pos: c.pos.slice(), block: c.block, stickers: c.stickers.map(function(s) {
						return { col: s.col, n: s.n.slice() };
					})
				};
			})
		};
	}

	/**
	 * does a twisty move [layerStart, layerEnd, face, q] turn the cubie at pos? (3x3x3 layers)
	 * @param {any[]} mv
	 * @param {number[]} pos
	 */
	function turns(mv, pos) {
		var layer = 2 - dot(pos, NORMALS[FACES.indexOf(mv[2])]); // 1 = the face layer, 3 = the far one
		return layer >= mv[0] && layer <= mv[1];
	}

	/**
	 * a turn is legal when every glued block is wholly inside or wholly outside the turning layers
	 * @param {any} st
	 * @param {any[]} mv
	 */
	function isLegal(st, mv) {
		if (FACES.indexOf(mv[2]) < 0) {
			return false;
		}
		var side = [];
		for (var i = 0; i < st.cubies.length; i++) {
			var c = st.cubies[i];
			var t = turns(mv, c.pos) ? 1 : 2;
			side[c.block] = (side[c.block] || 0) | t;
			if (side[c.block] == 3) {
				return false;
			}
		}
		return true;
	}

	/**
	 * apply a twisty move in place (legal or not: the caller checks)
	 * @param {any} st
	 * @param {any[]} mv
	 */
	function apply(st, mv) {
		var f = FACES.indexOf(mv[2]);
		if (f < 0) {
			return st;
		}
		var n = NORMALS[f];
		var q = ((mv[3] % 4) + 4) % 4;
		for (var i = 0; i < st.cubies.length; i++) {
			var c = st.cubies[i];
			if (!turns(mv, c.pos)) {
				continue;
			}
			for (var k = 0; k < q; k++) {
				c.pos = quarter(c.pos, n);
				for (var j = 0; j < c.stickers.length; j++) {
					c.stickers[j].n = quarter(c.stickers[j].n, n);
				}
			}
		}
		return st;
	}

	/**
	 * solved in any whole-puzzle orientation: every face shows one colour
	 * @param {any} st
	 */
	function isSolved(st) {
		var faceCol = {};
		for (var i = 0; i < st.cubies.length; i++) {
			var c = st.cubies[i];
			for (var j = 0; j < c.stickers.length; j++) {
				var key = c.stickers[j].n.join(',');
				if (key in faceCol && faceCol[key] != c.stickers[j].col) {
					return false;
				}
				faceCol[key] = c.stickers[j].col;
			}
		}
		return true;
	}

	var POW = { '': 1, "'": -1, '2': 2, "2'": -2 };

	/**
	 * parse a 3x3x3 move sequence into twisty moves (face turns, wide turns, slices, rotations); other tokens skipped
	 * @param {string} str
	 * @returns {any[][]}
	 */
	function parse(str) {
		var ret = [];
		var toks = String(str || '').split(/\s+/);
		for (var i = 0; i < toks.length; i++) {
			var m = /^([URFDLBurfdlbxyzMES])(w?)(2'|2|'|)$/.exec(toks[i]);
			if (!m) {
				continue;
			}
			var ch = m[1], p = POW[m[3]];
			var rot = { 'x': 'R', 'y': 'U', 'z': 'F' }[ch];
			var slice = { 'M': 'L', 'E': 'D', 'S': 'F' }[ch];
			if (rot) {
				ret.push([1, 3, rot, p]);
			} else if (slice) {
				ret.push([2, 2, slice, p]);
			} else if (ch != ch.toUpperCase() || m[2]) {
				ret.push([1, 2, ch.toUpperCase(), p]);
			} else {
				ret.push([1, 1, ch, p]);
			}
		}
		return ret;
	}

	/**
	 * the state after a sequence, from solved; illegal turns are skipped (never in a csTimer scramble)
	 * @param {string} str
	 */
	function run(str) {
		var st = solved();
		var mv = parse(str);
		for (var i = 0; i < mv.length; i++) {
			if (isLegal(st, mv[i])) {
				apply(st, mv[i]);
			}
		}
		return st;
	}

	/**
	 * what sits at a facelet: the sticker on face f (URFDLB) of the cubie at pos, as {col, block, cubie}, or null
	 * @param {any} st
	 * @param {number[]} pos
	 * @param {number} f
	 */
	function stickerAt(st, pos, f) {
		for (var i = 0; i < st.cubies.length; i++) {
			var c = st.cubies[i];
			if (!same(c.pos, pos)) {
				continue;
			}
			for (var j = 0; j < c.stickers.length; j++) {
				if (same(c.stickers[j].n, NORMALS[f])) {
					return { col: c.stickers[j].col, block: c.block, cubie: i };
				}
			}
		}
		return null;
	}

	// the virtual puzzles are twisty types (twisty/twistybandaged.js): register them next to $.TWISTY_RE (lib/utillib.js)
	var jq = /** @type {any} */ (typeof $ != 'undefined' ? $ : null);
	if (jq && jq.TWISTY_RE) {
		jq.TWISTY_RE += '|bic|bsq';
	}

	return {
		FACES: FACES,
		NORMALS: NORMALS,
		BLOCKS: BLOCKS,
		blockOf: blockOf,
		solved: solved,
		clone: clone,
		turns: turns,
		isLegal: isLegal,
		apply: apply,
		isSolved: isSolved,
		parse: parse,
		run: run,
		stickerAt: stickerAt
	};
})();
